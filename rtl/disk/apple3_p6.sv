// Combinational logic equivalent to the 341-0028 P6 sequencer PROM.
// Input pins and output feedback follow Apple drawing 050-0039-H, sheet 7.
// Exhaustively checked against both independently archived Apple III PROM dumps.
module apple3_p6(input wire [7:0] a, output wire [7:0] q);
    assign q[0] = (a[0] & a[3] & ~a[5] & ~a[6]) |
                  (a[0] & a[7] & ~a[1] & ~a[2] & ~a[3]) |
                  (a[6] & a[7] & ~a[1] & ~a[2] & ~a[3] & ~a[5]) |
                  (a[4] & a[5] & ~a[0] & ~a[1] & ~a[2] & ~a[3] & ~a[6]) |
                  (a[5] & ~a[0] & ~a[1] & ~a[2] & ~a[3] & ~a[6] & ~a[7]);
    assign q[1] = (a[2] & ~a[3]) |
                  (a[0] & a[2] & ~a[5] & ~a[6]);
    assign q[2] = (a[0] & a[6] & a[7] & ~a[1] & ~a[2] & ~a[3]) |
                  (a[0] & a[7] & ~a[1] & ~a[2] & ~a[3] & ~a[5]) |
                  (a[5] & ~a[0] & ~a[1] & ~a[2] & ~a[3] & ~a[6] & ~a[7]);
    assign q[3] = a[2] |
                  a[3] |
                  ~a[1] |
                  ~a[6] |
                  ~a[7] |
                  (a[0] & ~a[5]) |
                  (a[5] & ~a[0]) |
                  (~a[4] & ~a[5]);
    assign q[4] = (a[3] & ~a[5]) |
                  (a[4] & ~a[1] & ~a[2] & ~a[5]) |
                  (a[6] & ~a[2] & ~a[4] & ~a[5]) |
                  (a[6] & ~a[2] & ~a[5] & ~a[7]) |
                  (a[0] & a[1] & a[7] & ~a[2] & ~a[5]) |
                  (~a[0] & ~a[2] & ~a[5] & ~a[6]) |
                  (a[6] & ~a[1] & ~a[2] & ~a[3] & ~a[4]) |
                  (a[6] & ~a[2] & ~a[3] & ~a[4] & ~a[7]) |
                  (a[5] & a[7] & ~a[2] & ~a[3] & ~a[4] & ~a[6]) |
                  (a[0] & ~a[1] & ~a[2] & ~a[3] & ~a[4] & ~a[7]) |
                  (a[1] & ~a[0] & ~a[2] & ~a[3] & ~a[6] & ~a[7]) |
                  (a[0] & a[4] & a[7] & ~a[1] & ~a[2] & ~a[3] & ~a[6]);
    assign q[5] = (a[0] & a[3] & ~a[5]) |
                  (a[3] & a[5] & ~a[0]) |
                  (a[0] & a[4] & ~a[2] & ~a[5]) |
                  (a[0] & a[6] & a[7] & ~a[2] & ~a[5]) |
                  (a[4] & a[5] & ~a[0] & ~a[2] & ~a[6]) |
                  (a[4] & a[5] & ~a[0] & ~a[2] & ~a[7]) |
                  (a[1] & a[4] & a[6] & a[7] & ~a[2] & ~a[3]) |
                  (a[1] & a[5] & a[6] & a[7] & ~a[2] & ~a[3]) |
                  (a[5] & ~a[0] & ~a[2] & ~a[6] & ~a[7]);
    assign q[6] = (a[3] & a[6] & ~a[0]) |
                  (a[3] & a[6] & ~a[5]) |
                  (a[0] & a[3] & a[5] & ~a[6]) |
                  (a[0] & a[5] & ~a[2] & ~a[6]) |
                  (a[0] & a[6] & ~a[2] & ~a[5]) |
                  (a[6] & ~a[0] & ~a[2] & ~a[7]) |
                  (a[6] & ~a[1] & ~a[2] & ~a[5]) |
                  (a[6] & ~a[2] & ~a[3] & ~a[4]) |
                  (a[7] & ~a[2] & ~a[3] & ~a[4]) |
                  (a[0] & a[6] & a[7] & ~a[2] & ~a[3]) |
                  (a[1] & a[5] & a[6] & ~a[0] & ~a[2]) |
                  (a[0] & ~a[1] & ~a[2] & ~a[3] & ~a[4]);
    assign q[7] = (a[3] & a[7] & ~a[0]) |
                  (a[3] & a[7] & ~a[1]) |
                  (a[3] & a[7] & ~a[5]) |
                  (a[3] & a[7] & ~a[6]) |
                  (a[7] & ~a[2] & ~a[5]) |
